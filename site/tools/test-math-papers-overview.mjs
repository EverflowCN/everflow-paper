const manifest=JSON.parse(read('data/math-papers/active-collections.json'));
const set=JSON.parse(read('data/math-papers/zhangyu-2027-math2.json'));
assert.equal(manifest.collections.filter(x=>x.enabled).length,2);
assert.equal(manifest.collections.filter(x=>x.enabled&&x.category==='simulation').length,1);
assert.equal(manifest.collections.filter(x=>x.enabled&&x.category==='past').length,1);
assert.equal(set.papers.length,8);
assert.match(reader,/已做套卷图谱/);
assert.match(reader,/\/math\/27\/map\//);
assert.match(home,/data-math-sync/);
assert.match(reader,/await mathCloud.initialize\(registry\)/);
assert.match(reader,/mathCloud.update\(currentCollection,paper.id,patch\)/);
assert.match(map,/await cloud.initialize\(manifest\)/);
assert.match(map,/const included=\[\]/);
assert.match(map,/\.filter\(row=>reallyAttempted\(row.state\)\)/);
assert.match(map,/data-row=/);
assert.match(map,/data-q=/);
assert.match(map,/scrollIntoView/);
assert.match(map,/pointermove/);
assert.match(css,/overflow:auto/);
assert.match(css,/\.overview-column\{position:sticky/);
assert.match(css,/\.overview-row-label\{position:sticky/);
assert.match(css,/@media\(max-width:650px\)/);
assert.match(page,/data-overview-sync/);
assert.match(page,/data-detail-content/);
assert.match(page,/data-overview-filter/);
assert.match(cloud,/zhenti_sync_states/);
assert.match(cloud,/math2:/);
assert.match(cloud,/12\*60\*60\*1000/);
assert.match(cloud,/onAuthStateChange/);
assert.match(cloud,/::user:/);
assert.match(cloud,/auth-change|SIGNED_OUT/);
// A paper counts as 'done' only after an answer or an explicit self-evaluation.
const part=map.slice(map.indexOf('function reallyAttempted('),map.indexOf('function numbers(){'));
const {reallyAttempted}=new Function(part+';return {reallyAttempted}')();
assert.equal(reallyAttempted({}),false);
assert.equal(reallyAttempted({visited:['q1'],lastQuestion:1}),false);
assert.equal(reallyAttempted({answers:{q1:''}}),false);
assert.equal(reallyAttempted({answers:{q1:'B'}}),true);
assert.equal(reallyAttempted({judgements:{q2:'wrong'}}),true);
assert.equal(reallyAttempted({judgements:{q2:'correct'}}),true);
const first=set.papers[0].questions[0].id, second=set.papers[0].questions[1].id;
const firstTime='2026-10-10T01:00:00Z',secondTime='2026-10-10T02:00:00Z';
const isolate=cloud.slice(cloud.indexOf('function keys(p)'),cloud.indexOf('export function update(')).replace(/\bexport\s+/g,'');
const merge=new Function(`const clean=v=>v&&typeof v==='object'&&!Array.isArray(v)?v:{};
const stamp=v=>{const d=Date.parse(v||'');return Number.isFinite(d)?d:0};const now=()=>new Date().toISOString();${isolate};return {mergePaper,mergeRecords}`)();
const deviceA={answers:{[first]:'A'},judgements:{[first]:'wrong'},questionUpdatedAt:{[first]:firstTime},updatedAt:firstTime};
const deviceB={answers:{[second]:'B'},judgements:{[second]:'correct'},questionUpdatedAt:{[second]:secondTime},updatedAt:secondTime};
const combined=merge.mergePaper(deviceA,deviceB);
assert.equal(combined.answers[first],'A');
assert.equal(combined.answers[second],'B');
assert.equal(combined.judgements[first],'wrong');
assert.equal(combined.judgements[second],'correct');
// Clearing an old judgement on a newer device must propagate; no stale resurrection.
const cleared=merge.mergePaper(combined,{...combined,judgements:{[second]:'correct'},
  questionUpdatedAt:{...combined.questionUpdatedAt,[first]:'2026-10-10T03:00:00Z'},updatedAt:'2026-10-10T03:00:00Z'});
assert.equal(cleared.judgements[first],undefined);
assert.equal(cleared.answers[first],'A');
assert.equal(merge.mergeRecords({paper1:deviceA},{paper1:deviceB}).paper1.answers[second],'B');
console.log('Math reviewed-only overview, accessible 2D controls, account-scoped cloud LWW merge: OK');
