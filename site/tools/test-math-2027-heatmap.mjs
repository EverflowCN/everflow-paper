import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const root=new URL('../',import.meta.url);
const read=path=>readFileSync(new URL(path,root),'utf8');
const data=JSON.parse(read('data/math-papers/zhangyu-2027-math2.json'));
const reader=read('assets/js/math-2027-reader.js');
const style=read('assets/css/math-2027-reader.css');
const switcher=read('assets/js/question-bank-switch.js');
const entry=read('assets/js/zhenti-entry.js');
const html=read('math/27/index.html');
const mathjax=read('assets/js/math-2027-mathjax.js');
assert.equal(data.papers.length,8);
assert.ok(data.papers.every(p=>p.questions.length===22));
// Run the actual reader's pure heatmap status calculations, not a copy of the algorithm.
const begin=reader.indexOf('function heatStatus(');
const end=reader.indexOf('function heatmapHtml(');
assert.ok(begin>=0&&end>begin);
const isolated=reader.slice(begin,end);
const {heatStatus,heatCounts}=new Function('qualified',isolated+'\nreturn {heatStatus,heatCounts}')(q=>q?.verification==='proofread'&&Boolean(q.stem));
const paper=data.papers[0],qs=paper.questions,q=qs[0],q2=qs[1],q3=qs[2],q4=qs[3];
const record={answers:{[q.id]:'B',[q2.id]:'A'},judgements:{[q.id]:'correct',[q2.id]:'wrong'},visited:[q.id,q2.id,q3.id]};
assert.equal(heatStatus(q,record),'correct');
assert.equal(heatStatus(q2,record),'wrong');
assert.equal(heatStatus(q3,record),'visited');
assert.equal(heatStatus(q4,record),'unseen');
assert.equal(heatStatus(q4,{answers:{[q4.id]:'C'}}),'answered');
assert.equal(heatStatus({...q4,verification:'pending'},record),'locked');
const counts=heatCounts(paper,record);
assert.equal(counts.total,22);
assert.equal(counts.done,2);
assert.equal(counts.correct,1);
assert.equal(counts.wrong,1);
assert.equal(counts.visited,1);
assert.equal(counts.unseen,19);
assert.match(reader,/data-heatmap-paper/);
assert.match(reader,/data-heatmap-jump/);
assert.match(reader,/heatmapHtml\(paper,\{inReader:true\}\)/);
assert.match(style,/\.heatmap-grid/);
const registry=JSON.parse(read('data/math-papers/active-collections.json'));
assert.equal(registry.collections.filter(c=>c.enabled).length,1);
assert.equal(registry.collections[0].id,'zhangyu-2027-math2');
assert.equal(registry.collections[0].storageKey,'everflow-math2-2027-simulation-v1');
assert.match(reader,/library-collections/);
assert.match(reader,/data-collection-id/);
assert.match(reader,/categoryLabel\(id\)/);
assert.match(reader,/heatmapHtml\(p\)/);
assert.match(reader,/history\.replaceState\(null,'',`\?collection=/);
assert.match(reader,/paper\.questions\.length-1/);
assert.match(style,/\.main:has\(\.library-heading\) \.cards/);
assert.match(style,/\.main:has\(\.library-heading\) \.heatmap-wrap\.is-card \.heatmap-grid/);
assert.match(style,/@media\(max-width:620px\)/);
assert.doesNotMatch(reader,/math-papers\/catalog\.json/);

assert.match(reader,/HEAT_SYMBOLS=\{unseen:'',visited:'·',answered:'\?',correct:'✓',wrong:'×'/);
assert.match(reader,/蓝色 · 正确/);
assert.match(reader,/橙色 · 错误/);
assert.match(reader,/灰色 · 待判断\/未做/);
assert.match(style,/\.heat-cell\.heat-correct,\.heat-swatch\.heat-correct\{background:#1d4ed8/);
assert.match(style,/\.heat-cell\.heat-wrong,\.heat-swatch\.heat-wrong\{background:#9a3412/);
assert.match(style,/\.heat-cell\.heat-unseen,\.heat-swatch\.heat-unseen\{background:#e5e7eb/);
assert.match(style,/\.sheet button\.heat-correct\{background:#1d4ed8/);
assert.match(style,/\.sheet button\.heat-wrong\{background:#9a3412/);
assert.match(style,/\.judge-buttons button\[data-judge="correct"\]\[aria-pressed="true"\]\{border-color:#1d4ed8/);
assert.match(style,/\.judge-buttons button\[data-judge="wrong"\]\[aria-pressed="true"\]\{border-color:#9a3412/);
assert.doesNotMatch(reader,/绿色、红色/);

assert.match(style,/repeat\(11,minmax\(0,1fr\)\)/);
assert.match(html,/20261011-overview1/);
assert.match(html,/data-math-sync/);
assert.match(mathjax,/export async function typeset\(node\)/);
// No active navigation or imports for the legacy 107-paper catalogue.
assert.match(switcher,/27模拟卷/);
assert.match(switcher,/location\.assign\('\/math\/27\/'\)/);
assert.doesNotMatch(switcher,/math-papers\.js\?v=/);
assert.doesNotMatch(switcher,/math-papers\/catalog\.json/);
assert.match(entry,/location\.replace\('\/math\/27\/'\)/);
assert.match(entry,/localStorage\.setItem\('everflow-408-bank-source-v1','zhenti'\)/);
assert.doesNotMatch(reader,/math-papers-core\.js/);
assert.match(reader,/everflow-math2-2027-simulation-v1/);
// Published 2027 paper collection is the only available simulation collection.
assert.deepEqual(new Set(data.papers.map(p=>p.year)),new Set([2027]));
console.log('Math II 2027: eight accessible blue/orange/gray heatmaps with symbols; legacy bank disabled.');
